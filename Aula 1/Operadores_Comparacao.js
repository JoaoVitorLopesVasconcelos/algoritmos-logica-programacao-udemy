// Igual (==)
let igual = 5 == 5; // O operador de igualdade (==) compara apenas o valor.

// Estritamente igual (===)
let estritamenteIgual = 5 === 5; // O operador de igualdade estrita (===) compara o valor e o tipo da variável.

// Diferente (!=)
let diferente = 5 != 10; // O operador de diferença (!=) compara apenas o valor.

// Estritamente diferente (!==)
let estritamenteDiferente = 5 !== 10; // O operador de diferença estrita (!==) compara o valor e o tipo da variável.

// Maior que (>)
let maiorQue = 10 > 5; // O operador de maior que (>) compara o valor da variável da esquerda com o valor da variável da direita.

// Menor que (<)
let menorQue = 5 < 10; // O operador de menor que (<) compara o valor da variável da esquerda com o valor da variável da direita.

// Maior ou igual (>=)
let maiorOuIgual = 10 >= 10; // O operador de maior ou igual (>=) compara o valor da variável da esquerda com o valor da variável da direita.

// Menor ou igual (<=)
let menorOuIgual = 5 <= 10; // O operador de menor ou igual (<=) compara o valor da variável da esquerda com o valor da variável da direita.
