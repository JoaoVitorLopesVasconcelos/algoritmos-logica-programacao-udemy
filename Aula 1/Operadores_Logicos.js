// Operador Lógico "NÃO / Not" (!) - Inverte o valor da condição, ou seja, se for true retorna false e se for false retorna true.
console.log(!freteGratis);

// Dupla Negação (!!) - Converte o valor para booleano, ou seja, se for true retorna true e se for false retorna false.
const nome = "João";

console.log(!!nome);