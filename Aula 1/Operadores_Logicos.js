// Operador Lógico "E / And" (&&) - Retorna true se ambas as condições forem verdadeiras.
const freteGratis = true;
const estoque = false;

//console.log(freteGratis && estoque);

// Operador Lógico "OU / Or" (||) - Retorna true se pelo menos uma das condições for verdadeira.
