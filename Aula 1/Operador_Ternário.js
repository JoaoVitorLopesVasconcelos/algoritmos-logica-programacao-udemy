// Operador Ternário - Executa operação em linha, de maneira mais simples.

let media = 7;

if (media >= 7) {
    console.log("APROVADO")
} else {
    console.log("EXAME")
}

// Operação acima pode ser feita com o operador ternário da seguinte maneira:

media >= 7 ? console.log("APROVADO") : console.log("EXAME")

// O (:) seria o "se não".