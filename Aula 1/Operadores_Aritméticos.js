
// Adição (+)
let resultado = 1 + 10;

// Subtração (-)
resultado = 5 - 3;

// Multiplicação (*)
resultado = 10 * 3;

// Divisão (/)
resultado = 10 / 2.5;

// Módulo (%) - Pega o resto da divisão do primeiro valor pelo segundo valor.
resultado = 15 % 4;

// Incremento (++) - Adiciona 1 ao valor da variável.
let numero = 10;
numero++;

// Decremento (--) - Subtrai 1 do valor da variável.
numero--;


// Exponenciação (**) - Eleva o primeiro valor à potência do segundo valor.
let valor = 2 ** 4;

console.log(valor);