// Desafio teorema de pitagoras.
// O teorema de pitagoras diz que a soma dos quadrados dos catetos é igual ao quadrado da hipotenusa.
// A fórmula é: a² + b² = c², onde a e b são os catetos e c é a hipotenusa.

let catetoA = 5;
let catetoB = 10;
let calculoHipotenusa = Math.sqrt(catetoA ** 2 + catetoB ** 2); // Math.sqrt() é uma função que retorna a raiz quadrada de um número.
console.log(calculoHipotenusa); 